// Генерирует вымышленные желания для демо. Это не данные настоящих детей.
import { writeFileSync } from "node:fs";

const names = ["Амир", "Лола", "Сардор", "Малика", "Тимур", "Севара", "Рустам", "Камила", "Жасур", "Нигора", "Бобур", "Дильноза", "Азиз", "Мадина", "Шахзод", "Зарина", "Отабек", "Феруза", "Ильяс", "Сабина", "Данияр", "Алия", "Умид", "Гулноза", "Артур", "Яна", "Мирон", "София", "Руслан", "Милана"];
const cities = ["Ташкент", "Самарканд", "Бухара", "Андижан", "Наманган", "Фергана", "Нукус", "Карши"];
const wishes = [
  ["Футбольный мяч", "любит спорт и давно мечтает о собственном мяче для тренировок"],
  ["Набор для рисования", "мечтает стать художником и рисует всё, что видит вокруг"],
  ["Конструктор", "обожает собирать сложные модели и придумывать свои механизмы"],
  ["Большая мягкая игрушка", "хочет друга, с которым будет не страшно засыпать"],
  ["Настольная игра для всей семьи", "мечтает играть вечерами вместе с братьями и сёстрами"],
  ["Детская энциклопедия о космосе", "хочет знать про звёзды всё и мечтает полететь на Марс"],
  ["Машинка на пульте управления", "мечтает устраивать настоящие гонки во дворе"],
  ["Набор для рукоделия", "любит мастерить украшения и дарить их близким"],
  ["Школьный рюкзак", "хочет прийти в школу с красивым новым рюкзаком"],
  ["Самокат", "мечтает кататься по парку быстрее всех"],
  ["Кукольный домик", "придумывает целые истории и мечтает о доме для своих героев"],
  ["Набор юного учёного", "ставит опыты дома и хочет настоящую лабораторию"],
];

const rows = [];
for (let i = 1; i <= 150; i += 1) {
  const name = names[(i * 7) % names.length];
  const [title, story] = wishes[(i * 5) % wishes.length];
  const age = 4 + ((i * 3) % 11);
  const city = cities[(i * 11) % cities.length];
  const ward = `ONA-${String(i).padStart(4, "0")}`;
  const description = `${name} ${story}. Давай поможем этой мечте сбыться!`;
  rows.push(`  ('${ward}', ${i}, '${name}', ${age}, '${city}', '${title}', '${description}')`);
}

const sql = `-- Вымышленные желания для демо. На боевом проекте не применять: загрузите настоящие через импорт.
insert into public.wishes (ward_id, bulb_no, public_name, age, city, wish_title, description) values
${rows.join(",\n")};
`;
writeFileSync("supabase/seed_demo.sql", sql);
console.log("supabase/seed_demo.sql: 150 желаний");
